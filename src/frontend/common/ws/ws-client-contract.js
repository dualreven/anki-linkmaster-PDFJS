export function buildAllowedOutboundTypes(websocketMessageTypes) {
  const values = new Set();
  Object.values(websocketMessageTypes).forEach((v) => {
    if (typeof v === "string") {
      if (v.endsWith(":requested")) { values.add(v); }
      if (v.endsWith(":request")) { values.add(v); }
    }
  });
  return values;
}

